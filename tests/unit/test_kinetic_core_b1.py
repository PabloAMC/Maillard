def test_arrhenius_round_trip_at_the_reference_temperature():
    for key, parameter in MARTINS_M4.items():
        assert parameter.k_at(T_REF_K) == pytest.approx(parameter.k_ref, rel=1e-12), key


def test_arrhenius_matches_the_closed_form():
    parameter = MARTINS_M4["k_tdg_mel"]
    for temperature_k in (353.15, 373.15, 393.15, 473.15):
        expected = parameter.k_ref * math.exp(
            -(parameter.ea_kj_mol / R_KJ) * (1.0 / temperature_k - 1.0 / T_REF_K)
        )
        assert parameter.k_at(temperature_k) == pytest.approx(expected, rel=1e-12)


def test_arrhenius_is_monotone_increasing_in_temperature():
    for key, parameter in MARTINS_M4.items():
        assert parameter.k_at(353.15) < parameter.k_at(373.15) < parameter.k_at(393.15), key


def test_amadori_rate_is_derived_not_parameterised(parameters):
    k = rate_constants_at(parameters, T_REF_K)
    expected = (
        SCHIFF_AMADORI_SPLIT["ratio_amadori_over_schiff_pseudo_first_order"]
        * k["r_schiff"]
        * SCHIFF_AMADORI_SPLIT["amine_loading_mmol_L_for_the_ratio"]
    )
    assert k["r_amadori"] == pytest.approx(expected, rel=1e-12)


def test_the_schiff_amadori_split_ratio_barely_moves_the_trunk(parameters, monkeypatch):
    """
    The source REFUSES the Schiff/Amadori split, so the pinned ratio must not be
    strongly load-bearing.

    MEASURED, not asserted, and NOT zero: at 100 C / 120 min a 10x increase in
    the ratio (44.9 -> 449) moves the Amadori pool by -1.1% and the melanoidin
    sink by +7.5%. The mechanism is that the Schiff pool holds up ~2.5 mmol/L
    of amine at the pinned ratio; releasing it faster feeds the BIMOLECULAR
    melanoidin step, which is the most ratio-sensitive quantity in the network.

    This test pins that sensitivity at under 10% for a 10x ratio change rather
    than claiming it away. The consequence is recorded in the hold-out report:
    the split cannot explain a 1.45x browning bias, but it is not free either.
    """
    grid = np.array([0.0, 60.0, 120.0])
    base = integrate(parameters, 373.15, INITIAL, grid)
    from src.kinetic_core import network as network_module

    monkeypatch.setitem(
        network_module.SCHIFF_AMADORI_SPLIT,
        "ratio_amadori_over_schiff_pseudo_first_order",
        449.0,
    )
    moved = integrate(parameters, 373.15, INITIAL, grid)
    for label, a, b in (
        ("AMA", base.series("AMA")[-1], moved.series("AMA")[-1]),
        ("melanoidin", base.melanoidin_mmol_L()[-1], moved.melanoidin_mmol_L()[-1]),
        ("Glc", base.series("Glc")[-1], moved.series("Glc")[-1]),
    ):
        assert abs(b - a) / a < 0.10, f"{label}: {a} -> {b}"


