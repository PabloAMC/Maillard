def test_conservation_catches_a_stoichiometry_typo(parameters):
    """The invariant must actually be able to fail, or it proves nothing."""
    from src.kinetic_core import network
    from src.kinetic_core.species import BY_KEY, INDEX, SPECIES_KEYS

    broken = np.array(network.STOICHIOMETRY, copy=True)
    # delete the C5 residue that r_tdg_fa routes into FRAG_C
    broken[INDEX["FRAG_C"], network.REACTION_KEYS.index("r_tdg_fa")] = 0.0

    state = np.zeros(len(SPECIES_KEYS))
    state[INDEX["Glc"]] = 200.0
    state[INDEX["Gly"]] = 200.0
    state[INDEX["AMA"]] = 5.0
    state[INDEX["TDG"]] = 1.0
    rates = network.reaction_rates(state, rate_constants_at(parameters, 373.15))

    carbon = np.array([BY_KEY[key].carbon for key in SPECIES_KEYS], dtype=float)
    intact_drift = float(carbon @ (network.STOICHIOMETRY @ rates))
    broken_drift = float(carbon @ (broken @ rates))
    assert abs(intact_drift) < 1e-9
    assert abs(broken_drift) > 1e-6, "a deleted product must break the carbon balance"


