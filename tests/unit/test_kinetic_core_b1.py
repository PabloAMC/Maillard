def test_every_reaction_balances_carbon_and_nitrogen():
    validate_balance()
    for reaction in REACTIONS:
        for element in ("carbon", "nitrogen"):
            left, right = reaction.atom_balance(element)
            assert left == right, f"{reaction.key}: {element} {left} -> {right}"


def test_unbalanced_reaction_is_refused():
    bad = Reaction("r_bad", {"TDG": 1}, {"FA": 1}, "k_tdg_fa")  # loses 5 carbon
    with pytest.raises(ValueError, match="carbon does not balance"):
        validate_balance([bad])


def test_melanoidin_sink_is_terminal():
    for reaction in REACTIONS:
        assert "MEL_C" not in reaction.reactants
        assert "MEL_N" not in reaction.reactants
        assert "FRAG_C" not in reaction.reactants


@pytest.mark.parametrize("temperature_c", [100.0, 140.0, 180.0, 200.0])
def test_total_carbon_is_conserved(parameters, temperature_c):
    grid = np.linspace(0.0, 60.0, 41)
