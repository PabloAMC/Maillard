def test_the_browning_holdout_is_not_reachable_from_the_runtime_package():
    """
    epsilon = 0.64 L/(mmol*cm) and 282 L/(mol*cm) are the Module 4 hold-outs.
    Neither may appear anywhere in src/kinetic_core, and the measured-label map
    must not expose the melanoidin response to the fit objective.
    """
    assert "melanoidins" not in MEASURED_LABEL_TO_KEY
    assert "MEL_C" not in MEASURED_LABEL_TO_KEY.values()
    assert "MEL_N" not in MEASURED_LABEL_TO_KEY.values()

    import importlib

    held_out = (0.64, 640.0, 282.0, 0.282)

    def numbers_in(value, depth=0):
        if depth > 6:
            return
        if isinstance(value, bool):
            return
        if isinstance(value, (int, float)):
            yield float(value)
        elif isinstance(value, dict):
            for item in value.values():
                yield from numbers_in(item, depth + 1)
        elif isinstance(value, (list, tuple, set)):
            for item in value:
                yield from numbers_in(item, depth + 1)
        elif hasattr(value, "__dataclass_fields__") and not isinstance(value, type):
            for field in value.__dataclass_fields__:
                yield from numbers_in(getattr(value, field), depth + 1)

    for name in ("species", "parameters", "network", "integrate"):
        module = importlib.import_module(f"src.kinetic_core.{name}")
        for attribute, value in vars(module).items():
            if attribute.startswith("__"):
                continue
            for number in numbers_in(value):
                assert not any(
                    math.isclose(number, target, rel_tol=1e-12) for target in held_out
                ), f"src/kinetic_core/{name}.py exposes the held-out value {number}"


