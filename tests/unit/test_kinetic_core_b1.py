def test_martins_condition_regression(parameters):
    """
    100 C, glucose 200 mmol/L + glycine 200 mmol/L, 120 min, variant-A
    parameters. Pinned from the wave-B1 fit report; a change here means a
    change in the network or in a measured constant, and must be explained.
    """
    run = integrate(parameters, 373.15, INITIAL, [0.0, 120.0])
    end = {key: float(run.series(key)[-1])
           for key in ("Glc", "Fru", "Gly", "AMA", "TDG", "ODG", "MGO", "FA", "AA")}
    expected = {
        "Glc": 126.32, "Fru": 18.04, "Gly": 175.38, "AMA": 11.74,
        "TDG": 0.747, "ODG": 0.1274, "MGO": 3.416, "FA": 2.504, "AA": 11.25,
    }
    for key, value in expected.items():
        assert end[key] == pytest.approx(value, rel=2e-3), f"{key}: {end[key]}"

    assert float(run.melanoidin_mmol_L()[-1]) == pytest.approx(10.34, rel=2e-3)
    assert float(run.melanoidin_c_over_n()[-1]) == pytest.approx(9.51, rel=2e-3)


def test_melanoidin_c_over_n_starts_at_the_step_9_stoichiometry(parameters):
    """
    The first melanoidin formed is pure step-9 product, C8N1. Carbon-only
    additions (the fitted methylglyoxal channel) then raise the ratio, which is
    the direction Brands' elemental series measures.
    """
    run = integrate(parameters, 373.15, INITIAL, [0.0, 0.5, 60.0, 120.0])
    cn = run.melanoidin_c_over_n()
    # C/N can never fall below the step-9 repeat unit, and the carbon-only
    # channel is already contributing within the first half-minute.
    assert 8.0 <= cn[1] < 8.5, cn[1]
    assert cn[1] < cn[2] < cn[-1]


def test_every_intermediate_has_a_formation_and_a_consumption_term():
    """The defect this rebuild exists to fix: nothing may only accumulate."""
    produced, consumed = set(), set()
    for reaction in REACTIONS:
        produced.update(reaction.products)
        consumed.update(reaction.reactants)
    for key in ("Fru", "SB", "AMA", "TDG", "ODG", "MGO", "FA", "AA"):
        assert key in produced, f"{key} is never formed"
        assert key in consumed, f"{key} is never consumed"
    # the terminal pools are the declared exception
    for key in ("MEL_C", "MEL_N", "FRAG_C"):
        assert key in produced and key not in consumed


