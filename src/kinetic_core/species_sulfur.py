def ug_per_litre_to_mmol_per_litre(key: str, ug_per_litre: float) -> float:
    """Convert a printed ug/L (= ppb in water) anchor to mmol/L."""
    return float(ug_per_litre) / MOLECULAR_WEIGHT_G_PER_MOL[key] * 1.0e-3


def mmol_per_litre_to_ug_per_litre(key: str, mmol_per_litre: float) -> float:
    """The inverse, for reporting a prediction in the units it is printed in."""
    return float(mmol_per_litre) * MOLECULAR_WEIGHT_G_PER_MOL[key] * 1.0e3


# ---------------------------------------------------------------------------
# Element vectors and invariants over the EXTENDED state
# ---------------------------------------------------------------------------


def element_vector(element: str) -> Tuple[int, ...]:
    return tuple(getattr(s, element) for s in SULFUR_STATE)


def total_element(state, element: str) -> float:
    return float(
        sum(n * float(state[i]) for i, n in enumerate(element_vector(element)))
    )


def total_sulfur_extended(state) -> float:
    """Total sulfur, mmol S/L, over the extended state including every sink."""
    return total_element(state, "sulfur")


def initial_sulfur_state(concentrations: Mapping[str, float]):
    """Build an extended state vector from a {species_key: mmol/L} mapping."""
    import numpy as np

    y0 = np.zeros(N_SULFUR_STATE, dtype=float)
    for key, value in concentrations.items():
        if key not in SULFUR_INDEX:
            raise KeyError(
                f"unknown species {key!r}; expected one of {SULFUR_STATE_KEYS}"
            )
        if float(value) < 0.0:
            raise ValueError(f"negative initial concentration for {key!r}")
        y0[SULFUR_INDEX[key]] = float(value)
    return y0


def sulfur_state_as_dict(state) -> Dict[str, float]:
    return {key: float(state[SULFUR_INDEX[key]]) for key in SULFUR_STATE_KEYS}


