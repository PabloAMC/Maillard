#: so that a missing OAV is visibly a gap rather than a silent zero.
NO_THRESHOLD_AVAILABLE: Tuple[str, ...] = (
    "FFTD", "MMFT", "MP3P", "MP2P", "MESH", "MP", "NF", "H2S",
)


def odour_activity_values(state) -> Dict[str, object]:
    """
    OAV per species, plus the dimer-vs-monomer comparison that qualifies the
    whole thiol-consumption module.

    Returns floats for the five species with a threshold and the string
    ``'no_threshold_available'`` for the eight without. There is no default
    threshold and no imputation.
    """
    out: Dict[str, object] = {}
    for key, threshold in ODOUR_THRESHOLD_UG_PER_L.items():
        ug = mmol_per_litre_to_ug_per_litre(key, state[SULFUR_INDEX[key]])
        out[key] = ug / threshold
    for key in NO_THRESHOLD_AVAILABLE:
        out[key] = "no_threshold_available"
    mft = out.get("MFT", 0.0)
    dimer = out.get("MFTD", 0.0)
    out["dimer_over_monomer_OAV"] = (
        float(dimer) / float(mft) if isinstance(mft, float) and mft > 0 else float("nan")
    )
    out["potency_ratio_dimer_over_monomer"] = (
        ODOUR_THRESHOLD_UG_PER_L["MFT"] / ODOUR_THRESHOLD_UG_PER_L["MFTD"]
    )
    out["threshold_provenance"] = (
        "Zhou 2023 SI Table S2. basis_declared=true, provenance=unknown (the SI "
        "prints no citation for any threshold). Model INPUT, never a scored "
        "prediction."
    )
    return out
