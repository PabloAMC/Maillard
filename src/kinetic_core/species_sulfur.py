"""
src/kinetic_core/species_sulfur.py

THE SULFUR EXTENSION OF THE STATE VECTOR (Build Wave B2), WITH ITS CARBON,
NITROGEN AND SULFUR BOOKKEEPING.
=============================================================================

Build Wave B1 declared thirteen sulfur-free trunk species in ``species.py``.
This module APPENDS the sulfur block and publishes the CONCATENATED table.
Nothing in B1's table is edited, reordered or removed: the first
``len(SPECIES)`` entries of ``SULFUR_STATE`` are B1's, in B1's order, so a
trunk state vector is a prefix of a sulfur state vector and every B1 index is
still valid.

WHY THREE ACCOUNTING POOLS AND TWO SITE POOLS
---------------------------------------------
B1 routes unmeasured carbon into ``FRAG_C`` rather than deleting it. The sulfur
network needs the same discipline on two more elements and on two things that
are not elements at all:

  * ``FRAG_N`` / ``FRAG_S`` -- unassigned fragment nitrogen and sulfur. Cysteine
    thermolysis reports the H2S and nothing else; thiamine cleavage reports the
    C5 sulfur fragment and nothing else. The other atoms exist. They go here so
    the S and N invariants close as EQUALITIES.

  * ``MELE`` -- the MATRIX ELECTROPHILE SITE POOL, and ``OX`` -- OXIDANT
    EQUIVALENTS. Both carry ZERO atoms of every element, because neither is a
    molecule: ``MELE`` is a titrated site density (Charles-Bernard 2005:
    8-10 mmol per g dry coffee solids, by hydroxylamine titration) and ``OX``
    is a redox equivalent. They are declared ``role='site'`` and are exempt from
    nothing -- they balance trivially because they contain nothing. Their
    purpose is that both are DEPLETABLE, which is what makes the thiol sink a
    bimolecular, saturating channel rather than an eternal first-order drain.
    That distinction is the whole content of the Hofmann-2002 80 C brew
    hold-out, whose measured anomaly (the brew is SLOWER than the 30 C model
    systems) the dossier attributes to exactly this pool being partly consumed
    during extraction.

WHAT IS *NOT* HERE
------------------
Pyrazines, Sotolon, 2-acetyl-1-pyrroline, butane-2,3-dione and the thiazole
family beyond 2-acetylthiazole. They are declared out of scope for this wave in
``sulfur.py``'s OUT_OF_SCOPE block, with the FIT rows they strand named.

UNITS: mmol/L, minutes, Kelvin, kJ/mol -- B1's units, unchanged.
"""

