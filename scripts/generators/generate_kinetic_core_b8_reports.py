def _exam_row_map(payload: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
    out = {}
    for row in payload.get("rows", []):
        key = (row.get("benchmark_id"), row.get("compound"),
               row.get("temp_C"), row.get("time_min"))
        out[repr(key)] = row
    return out


def _fold(row: Optional[Dict[str, Any]]) -> Optional[float]:
    if row is None:
        return None
    v = row.get("core_fold_error")
    return float(v) if isinstance(v, (int, float)) else None


