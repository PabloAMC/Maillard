def run_panel(fit_report: Path, basename: str) -> Dict[str, Any]:
    import generate_kinetic_core_b2_3_holdout as PANEL
    PANEL.FIT_REPORT = fit_report
    PANEL.OUT_BASENAME = basename
    rc = PANEL.main(["--basename", basename])
    if rc != 0:
        raise SystemExit(f"panel returned {rc} for {fit_report}")
    return json.loads((V / f"{basename}.json").read_text())


def run_exam(fit_report: Path, basename: str) -> Dict[str, Any]:
    import generate_cutover_final_exam as EXAM
    from src.kinetic_core import engine
    previous = engine._B2_FIT_REPORT
    try:
        engine._B2_FIT_REPORT = fit_report
        payload = EXAM.build_exam(target_tag="meaty")
    finally:
        engine._B2_FIT_REPORT = previous
    payload["parameters_from"] = str(fit_report.relative_to(ROOT))
    payload["wave_column"] = basename
    (V / f"{basename}.json").write_text(
        json.dumps(payload, indent=2, sort_keys=True, default=str))
    (V / f"{basename}.md").write_text(EXAM.render_markdown(payload))
    return payload


