def _fmt(value, spec="{:.3g}", dash="--"):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return dash
    # NaN is what a row with no fold error carries -- a directional or
    # sign-test row. Printing "nanx" reads as a broken number; printing "--"
    # reads as what it is, which is "this row does not have a fold".
    if value != value or value in (float("inf"), float("-inf")):
        return dash
    return spec.format(value)


