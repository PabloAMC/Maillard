"""
Build Wave B8 -- THE BLIND RE-SITS, and the two reports.

Nothing here fits anything. There is no optimiser in this file, no bounds and no
`least_squares` import. It runs two EXISTING scorers at frozen parameter sets and
assembles what they say.

THE DECOMPOSITION, AND IT IS THE POINT OF THE FILE
--------------------------------------------------
`d1_exam_panel_reconciliation.md` found that 96 % of the B2.2 -> B2.3 exam
regression was caused by an undeclared change of objective rather than by the
physics that wave shipped. B8 changes BOTH physics and parameters, so it scores
THREE columns and never two:

  PRE-B8      the artifacts already on disk at HEAD -- B2.3's vector under the
              pre-B8 code. This is what shipped before this wave.
  PHYSICS     B2.4-half's OWN vector, unrefitted, under B8's T-structure. The
              barriers moved; not one rate constant did.
  B8          B8's refitted vector under B8's T-structure. The ship.

PRE-B8 -> PHYSICS is what the measurements cost or bought on their own.
PHYSICS -> B8 is what the refit recovered. Reporting only the ends would let a
refit take credit for a measurement, or a measurement take the blame for a refit.

FIREWALL. `data/benchmarks/external_validation/` is opened by
`generate_cutover_final_exam` and by nothing else. This file reads the scorers'
own output.

Usage
-----
    python scripts/generators/generate_kinetic_core_b8_reports.py --all
"""

