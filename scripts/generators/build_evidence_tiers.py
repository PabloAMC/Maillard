BASELINE = data_paths.VALIDATION_DIR / "incumbent_evidence_tiers_baseline.json"
PARAMETER_SOURCES = sorted((ROOT / "src" / "kinetic_core").glob("parameters*.py")) + [
    ROOT / "src" / "evidence_tiers.py", ROOT / "src" / "kinetic_core" / "acrylamide_conditions.py"]


def _f(x, nd=2):
    if x is None:
        return "—"
    if isinstance(x, float):
        return f"{x:.{nd}f}" if abs(x) >= 10 ** (-nd) or x == 0 else f"{x:.2e}"
    return str(x)


def _band(row) -> str:
    b = row.get("band")
    if not b:
        return "**none**" if row["tier"] in ("analogue", "fitted_unidentified") else "—"
    w = b.get("width_dex")
    what = b.get("distribution") or ""
    if b.get("lo") is not None and b.get("hi") is not None:
        what += f" [{_f(b['lo'])}, {_f(b['hi'])}]"
    elif b.get("sigma"):
        what += f" sigma {_f(b['sigma'])}"
    elif b.get("half_width"):
        what += f" +/- {_f(b['half_width'], 3)}"
    if row.get("band_is_search_bound"):
        what += " **= the search bounds, not a band (S4)**"
    return f"{what.strip()}{'' if w is None else f' ({w:.2f} dex)'}{'' if b.get('sampled') else ', not sampled'}"


def markdown(payload: dict) -> str:
    s = payload["summary"]
    rows = payload["rows"]
    tiers = list(payload["rules"]["tiers"]) + (["unclassified"] if s["unclassified"] else [])
    L = ["# The incumbent evidence audit (plan sec. 7, rule S1)", "",
         "*Generated by `scripts/generators/build_evidence_tiers.py` from `src/evidence_tiers.py`, a pure reader of the "
         "shipped parameters, the frozen fit reports and their Laplace / slice-profile artifacts, B38, the envelope's "
         "priors, the sulfur flux evidence, the data wishlist and the registers. One row per COORDINATE (log10 k_ref and "
         "Ea separately) and per band-carried parameter. Moves no constant; do not edit by hand.*", "",
         "**How to read a tier.** `measured`: a direct measurement of that step under comparable conditions. `analogue`: "
         "a same-class measurement transferred (its band, or **none** when no band is declared). `bounded`: only a "
         "measured or physical bound; one- or two-sided as stated. `fitted_identified`: a converged fit whose MARGINAL "
         "profile pins it with every other unidentified coordinate profiled over its band; any one unidentified "
         "criterion (band edge, flat or bound-limited slice, a CI spanning the band or reaching an unphysical sign, no "
         "uncertainty, frozen since an unidentified fit, B38 UNIDENTIFIED / AT_BOUND) overrides a reported stderr. "
         "`fitted_unidentified`: the rest of the fitted coordinates. `structural`: a declared structural assumption (a "
         "declared zero, an inert arm, a declared barrier of zero, a declared band with no source). `physical_constant`, "
         "`conflicting_measurements` (direct measurements disagree beyond their errors), `withdrawn`.", "",
         f"**{s['coordinates']} coordinates.** "
         + ", ".join(f"{t} {s['by_tier'][t]}" for t in tiers if s["by_tier"].get(t)) + ".", "",
         "**No coordinate is `fitted_identified`.** No artifact on disk profiles a coordinate with the other "
         "unidentified coordinates profiled over their bands (the B8 / B9 / B51 / B60 slice profiles hold them at the "
         "optimum; Laplace and B38 are local). Of the fitted coordinates, "
         f"{s['fitted_identification_status'].get('unidentified', 0)} fail a local criterion and "
         f"{s['fitted_identification_status'].get('locally_pinned_profile_missing', 0)} pass every local criterion but "
         "lack that profile (`identification.status` = `locally_pinned_profile_missing`): a profile run with the "
         "unidentified coordinates free would decide those.", "",
         "## 1. Tiers by lane", "", "| lane | " + " | ".join(tiers) + " |", "|---|" + "---|" * len(tiers)]
    for lane, d in s["by_lane"].items():
        L.append(f"| {lane} | " + " | ".join(str(d.get(t, 0)) for t in tiers) + " |")
    L += ["", "| coordinate kind | " + " | ".join(tiers) + " |", "|---|" + "---|" * len(tiers)]
    for kind, d in s["by_coordinate_kind"].items():
        L.append(f"| {kind} | " + " | ".join(str(d.get(t, 0)) for t in tiers) + " |")
    def contradiction_table(entries):
        out = ["| coordinate | measurement | sources | size (dex) | 95 % interval (dex) | S4 route | status | sensitivity | species of its steps |",
               "|---|---|---|---|---|---|---|---|---|"]
        for e in entries:
            out.append(f"| `{e['coordinate']}` | {e['measurement']} | {', '.join(e['sources'])} | {e['size_dex']:+.2f} | "
                       f"{'undefined' if e['interval95_halfwidth_dex'] is None else '+/- ' + _f(e['interval95_halfwidth_dex'])} | "
                       f"{e['s4_route']} | {e['s2_status']} | {e['sensitivity']} | {', '.join(e['outputs'] or []) or '—'} |")
        return out

    L += ["", "## 2. S2 and the contradicted coordinates", "",
          "Sec. 7 S2 (final, 066684b7) targets **fitted-identified** coordinates only. The record has none (sec. 1), so "
          f"**S2 has {len(s['s2_candidates'])} candidates**; no measurement can replace a constant before the profiles "
          "exist. Each direct measurement that contradicts a fitted-unidentified coordinate is instead an S4 source: a "
          "**band** when it constrains the value, a **rival** when it implies a different rate law or species. Ranked by "
          "output sensitivity, then size. The 95 % interval is S2 (b)'s: reported noise, within-lab between-paper spread, "
          "the between-lab term (the step's measured spread with >= 2 laboratories, else the lane's: "
          f"{payload['rules']['lane_between_lab_source']}) and the coordinate's own interval, in quadrature; undefined when "
          "a condition the step depends on is unstated.", ""]
    L += contradiction_table(s["s2_candidates"]) if s["s2_candidates"] else ["*S2 candidates: none.*"]
    L += ["", "**Contradicting fitted-unidentified coordinates (S4 band / rival sources):**", ""]
    L += contradiction_table(s["s4_sources_contradicting_unidentified"])
    L += ["", "**Contradicted, not fitted (S2 does not apply; an S4 source and a CF entry):**", ""]
    L += [f"- `{e['coordinate']}` ({e['tier']}): {e['measurement']} ({', '.join(e['sources'])}), {e['size_dex']:+.2f} dex"
          for e in s["contradicted_non_fitted"]] or ["- none"]
    L += ["", "**One-sided bounds satisfied (not contradictions):**", ""]
    L += [f"- `{e['coordinate']}`: {e['measurement']} — {e['status']}" for e in s["one_sided_bounds_satisfied"]] or ["- none"]
    L += ["", "### The measurement records (what S2 (a) - (d) must match)", ""]
    for r in rows:
        for c in r["contradicted_by"]:
            L += [f"**{c['id']} — `{r['id']}`** ({r['tier']}): {c['measurement']}.",
                  f"- sources {', '.join(c['sources'])}; ledger rows {', '.join(c['ledger_rows']) or 'none'} ({c['ledger_note']}); {c['cite']}",
                  f"- laboratory: {c['lab']}",
                  f"- system: {c['system']}",
                  f"- channels: {c['channels']} (relation: `{c['relation']}`)",
                  f"- rate law measured: {c['rate_law']}; engine: {c['engine_rate_law']}",
                  f"- concentration: {c['concentration']}; unstated: {', '.join(c['unstated']) or 'none'}",
                  f"- conditions the step depends on, unstated: {', '.join(c['depends_on_unstated']) or 'none'}; "
                  f"inferred bound / patent: {'yes' if c['inferred_bound'] else 'no'}",
                  f"- size: {c['size_note']} -> {c['size_dex']:+.2f} dex; 95 % interval: {c['interval_rule']}"
                  + ("" if c["z"] is None else f"; z {c['z']:+.2f}, two-sided p {c['p_two_sided']:.2g}"),
                  "- matches (S2 (a)): " + ", ".join(f"{k} {'yes' if v else '**no**'}" for k, v in c["matches"].items()),
                  f"- S4 route: **{c['s4_route']}** ({c['s4_route_reason'] or '—'})",
                  f"- **{c['s2_status']}**. {c['note']}", ""]
    L += ["## 3. S4: fitted-unidentified coordinates with high output sensitivity", "",
          "A local unidentified criterion fails AND the step matters (sulfur flux attribution: > 1 % of a pot's flux or "
          "of an odorant-path species) or B38's Jacobian norm is >= 1. Under S4 a band is a measured bound, an analogue "
          "or a reaction-class distribution; **a search bound is never a band**, so a coordinate with only a search "
          "bound has NO band and its outputs are refused until one is sourced. Order: no legitimate band first, then "
          "held fixed by the envelope, then impact = span (the band, else the search span, for ranking only) x the "
          "largest flux / odorant-path share. These are the outputs that should widen or be refused.", "",
          "| coordinate | envelope samples it | band (dex) | search span (dex) | odorant-path share | pot-flux share | B38 norm | why unidentified | species of its steps |",
          "|---|---|---|---|---|---|---|---|---|"]
    for e in s["s4_sensitive_unidentified"]:
        L.append(f"| `{e['coordinate']}` | {'yes' if e['envelope_samples_it'] else '**no**'} | "
                 f"{'**none**' if e['band_width_dex'] is None else _f(e['band_width_dex'])} | {_f(e['search_bounds_span_dex'])} | "
                 f"{_f(e['max_odorant_path_share'])} | {_f(e['max_pot_flux_share'])} | {_f(e['b38_sensitivity_norm'])} | "
                 f"{'; '.join(e['why_unidentified'])} | {', '.join(e['outputs'] or []) or '—'} |")
    L += ["", "## 4. Label conflicts: an existing record says identified, a criterion says not", "",
          "| coordinate | label source | label | failing criteria |", "|---|---|---|---|"]
    L += [f"| `{c['coordinate']}` | {c['label_source']} | {c['label']} | {'; '.join(c['fails'])} |" for c in s["label_conflicts"]]
    L += ["", "## 5. Fit rows later withdrawn or corrected", "",
          "| fit | row | kind | issue | size (dex) | cite |", "|---|---|---|---|---|---|"]
    L += [f"| {w['fit']} | `{w['row']}` | {w['kind']} | {w['issue']}"
          + ("" if "row_present_in_frozen_report" not in w else
             f" (row in the frozen report: {'yes' if w['row_present_in_frozen_report'] else '**no**'})")
          + f" | {w['size_dex']:+.2f} | {w['cite']} |" for w in payload["withdrawn_or_corrected_fit_rows"]]
    flagged = sorted({r['id'] for r in rows if r['fit_rows_withdrawn_or_corrected']})
    L += ["", f"Coordinates whose fit read such a row: {len(flagged)} — " + ", ".join(f"`{x}`" for x in flagged), ""]
    rec = s["unidentified_lists_reconciled"]
    L += ["## 6. The two existing unidentified lists, reconciled", "",
          f"- `data_wishlist.json` sec. 1 ({len(rec['data_wishlist_sec1'])}): {', '.join(rec['data_wishlist_sec1'])}",
          f"- `docs/reference/unpinned_constants.yml` ({len(rec['unpinned_constants_yml'])}): {', '.join(rec['unpinned_constants_yml'])}",
          f"- `sulfur_reaction_evidence.json` unpinned that matter ({len(rec['sulfur_evidence_unpinned_that_matter'])}): "
          f"{', '.join(rec['sulfur_evidence_unpinned_that_matter'])}",
          f"- on both lists: {', '.join(rec['in_both_lists']) or 'none'}. {rec['why_disjoint']}",
          f"- unidentified sulfur rates here on neither list (they do not matter in the eight reference pots, or matter "
          f"only through the barrier): {', '.join(rec['unidentified_here_on_neither_list']) or 'none'}",
          f"- on a list but not unidentified here: {', '.join(rec['on_a_list_but_not_unidentified_here']) or 'none'}", "",
          "## 7. Vocabularies mapped onto the tiers", ""]
    for name, m in payload["vocabulary_map"].items():
        L.append(f"- **{name}** — {'keep' if m['keep'] else '**retire**'}: {m['why']}")
        L += [f"  - `{k}` -> {v}" for k, v in m.items() if k not in ("keep", "why")]
    L += ["", "## 8. The incumbent's structural choices", "",
          f"{len(s['structural_choices_without_a_case'])} of {len(payload['structural_choices'])} never had a case.", "",
          "| id | choice | where | evidence against | case | choice register |", "|---|---|---|---|---|---|"]
    L += [f"| {c['id']} | {c['choice']} | `{c['where']}` | {c['against']} | {c['case']} | {c['choice_register']} |"
          for c in payload["structural_choices"]]
    L += ["", "## 9. Gaps", "",
          f"- analogue coordinates with no declared band ({len(s['analogue_without_a_declared_band'])}): "
          + ", ".join(f"`{x}`" for x in s["analogue_without_a_declared_band"]),
          f"- unclassified ({len(s['unclassified'])}): " + (", ".join(f"`{u['coordinate']}` ({u['basis']})" for u in s["unclassified"]) or "none"),
          "- tier changes since the frozen baseline (`docs/reference/evidence_tier_changes.yml`; upgrades need an "
          "artifact and a second reader, downgrades a citation; `scripts/ci/evidence_tier_gate.py`): "
          + (", ".join(f"`{r['id']}` {c.get('from')} -> {c.get('to')}" for r in rows for c in r.get("tier_changes") or [])
             or "none"),
          "", "## 10. Every coordinate", "",
          "| coordinate | lane | value | tier | band | basis | conflicts named | sensitivity |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        val = r.get("value")
        val = _f(val, 3) if isinstance(val, (int, float)) else ("simplex" if isinstance(val, dict) else (r.get("value_note") or "—"))
        sides = f" ({r['bounded_sides']})" if r.get("bounded_sides") else ""
        cf = ", ".join(f"{c['id']} ({c['status']})" for c in r.get("conflicts_named") or []) or "—"
        sens = r["sensitivity"]
        sens_s = sens["class"]
        if sens.get("max_odorant_path_share") is not None:
            sens_s += f" (odorant {sens['max_odorant_path_share']:.0%}, flux {sens['max_pot_flux_share']:.1%})"
        elif sens.get("b38_sensitivity_norm") is not None:
            sens_s += f" (B38 {sens['b38_sensitivity_norm']:.2g})"
        basis = (r.get("basis") or "").replace("|", "/")
        L.append(f"| `{r['id']}` | {r['lane']} | {val} | {r['tier']}{sides} | {_band(r)} | {basis[:220]} | {cf} | {sens_s} |")
    return "\n".join(L) + "\n"


def build() -> dict:
    record = evidence_tiers.build_record()
    inputs = [Path(p) for p in record.pop("inputs")] + PARAMETER_SOURCES
    return {"artifact": "incumbent_evidence_tiers",
            "provenance": provenance.provenance_block("incumbent_evidence_tiers",
                                                      generated_by="scripts/generators/build_evidence_tiers.py",
                                                      inputs=inputs),
            **record}


def baseline(payload: dict) -> dict:
    """The tiers at the audit, frozen: what every later tier is checked against (sec. 7 S1)."""
    return {"artifact": "incumbent_evidence_tiers_baseline",
            "frozen": {"date": provenance.today_iso(), "git": provenance.git_head(),
                       "from": data_paths.rel(OUT),
                       "rule": "write-once. A row whose tier differs from this one needs its change(s) in "
                               "docs/reference/evidence_tier_changes.yml: an upgrade with an artifact and a second "
                               "reader, a downgrade with a citation (plan sec. 7 S1; scripts/ci/evidence_tier_gate.py)"},
            "tiers": {r["id"]: r["tier"] for r in payload["rows"]}}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--freeze-baseline", action="store_true",
                        help=f"also write {data_paths.rel(BASELINE)} (write-once)")
    args = parser.parse_args(argv)
    if args.freeze_baseline and BASELINE.exists():
        print(f"{data_paths.rel(BASELINE)} exists and is write-once; a tier change goes in "
              "docs/reference/evidence_tier_changes.yml", file=sys.stderr)
        return 1
    payload = build()
    OUT.write_text(json.dumps(payload, indent=1, default=str) + "\n", encoding="utf-8")
    OUT.with_suffix(".md").write_text(markdown(payload), encoding="utf-8")
    s = payload["summary"]
    print(f"wrote {data_paths.rel(OUT)}: {s['coordinates']} coordinates; {s['by_tier']}; "
          f"{len(s['s2_candidates'])} S2 candidates, {len(s['s4_sensitive_unidentified'])} S4, "
          f"{len(s['label_conflicts'])} label conflicts")
    if args.freeze_baseline:
        BASELINE.write_text(json.dumps(baseline(payload), indent=1) + "\n", encoding="utf-8")
        print(f"froze {data_paths.rel(BASELINE)}: {len(payload['rows'])} tiers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
