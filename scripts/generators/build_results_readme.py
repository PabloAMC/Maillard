def tracked_files() -> List[Path]:
    out = subprocess.run(["git", "ls-files", "results"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return [Path(line) for line in out.splitlines()
            if line and Path(line).name not in SKIP_BASENAMES and line != "results/README.md"]


def _is_glob(key: str) -> bool:
    return any(ch in key for ch in "*?[")


def covering_key(rel: Path) -> Optional[str]:
    """The most specific DESCRIPTIONS key that covers ``rel`` (exact > glob > directory)."""
    text = str(rel)
    if text in DESCRIPTIONS:
        return text
    for key in DESCRIPTIONS:
        if _is_glob(key) and fnmatch.fnmatchcase(text, key):
            return key
    for parent in rel.parents:
        if str(parent) in DESCRIPTIONS and not _is_glob(str(parent)):
            return str(parent)
    return None


def build() -> str:
    files = tracked_files()
    problems: List[str] = []
    cover: Dict[str, List[Path]] = defaultdict(list)
    for rel in files:
        key = covering_key(rel)
        if key is None:
            problems.append(f"undescribed: {rel}")
        else:
            cover[key].append(rel)
    for key in DESCRIPTIONS:
        if _is_glob(key):
            if not cover.get(key):
                problems.append(f"described but matches nothing: {key}")
        elif not (ROOT / key).exists():
            problems.append(f"described but absent: {key}")
    if problems:
        raise SystemExit("results/README.md cannot be built:\n  " + "\n  ".join(problems))

    by_dir: Dict[str, List[Tuple[str, List[Path]]]] = defaultdict(list)
    for key, matched in cover.items():
        directory = str(Path(key).parent) if not (ROOT / key).is_dir() else str(Path(key).parent)
        by_dir[directory].append((key, sorted(matched)))

    lines = [
        "# `results/` — generated artifacts",
        "",
        "> Generated by `scripts/generators/build_results_readme.py` from `git ls-files results` and a hand-written",
        "> description map in that script. Do not edit this file; edit the map and re-run. A tracked file with no",
        "> description, or an entry that matches nothing, fails the build (`tests/unit/test_results_readme.py`).",
        "",
        "Everything here is written by code from `data/` and the frozen parameters; nothing here is curated input.",
        "Two kinds of file live side by side: **live artifacts** that an alias in `scripts/docker_maillard.sh`",
        "regenerates (`core-scores`, `core-directional`, `core-envelope`, `model-card`, ...) and whose freshness",
        "`scripts/ci/artifact_freshness_gate.py` checks; and **frozen records** of the fit / hold-out waves",
        "(`scripts/generators/WAVES.md`: not re-run, a change is a new wave). Every live artifact carries a",
        "`provenance` block (git head, date, input hashes: `src/provenance.py`).",
        "",
        f"Tracked files: **{len(files)}**. Local-only (gitignored): scratch runs under `results/quickstart/`, `results/user/`.",
        "",
    ]
    for directory in sorted(by_dir, key=lambda d: (d.count("/"), d)):
        lines.append(f"## `{directory}`")
        lines.append("")
        lines.append("| files | what it is, who writes it, who reads it |")
        lines.append("|---|---|")
        for key, matched in sorted(by_dir[directory], key=lambda kv: kv[0]):
            if (ROOT / key).is_dir():
                label = f"`{Path(key).name}/` ({len(matched)} files)"
            elif _is_glob(key):
                names = ", ".join(f"`{p.name}`" for p in matched[:4]) + (" …" if len(matched) > 4 else "")
                label = f"`{Path(key).name}` ({len(matched)}): {names}"
            else:
                label = f"`{Path(key).name}`"
            lines.append(f"| {label} | {DESCRIPTIONS[key]} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if results/README.md is stale")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        if (OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else "") != text:
            print(f"{data_paths.rel(OUTPUT)} is stale; re-run without --check", file=sys.stderr)
            return 1
        print(f"{data_paths.rel(OUTPUT)} is current")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {data_paths.rel(OUTPUT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
